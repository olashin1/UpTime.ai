"""Score saved eval results and write eval/results/metrics.md + metrics.json.

    backend/.venv/Scripts/python eval/score.py

Percentiles use the nearest-rank method (p95 of 20 values = the 19th smallest).
"""

import json
import math

from common import RESULTS_DIR, load_cases

MODES = [("rules", "Rules (original)"), ("llm", "LLM, no context"), ("llm_repo", "LLM + GitHub context")]


def load(name: str) -> dict | None:
    path = RESULTS_DIR / f"{name}.json"
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None


def pct(numerator: int, denominator: int) -> str:
    return f"{numerator}/{denominator} ({100 * numerator / denominator:.1f}%)" if denominator else "n/a"


def nearest_rank(values: list[int], p: float) -> int:
    ordered = sorted(values)
    return ordered[max(1, math.ceil(p / 100 * len(ordered))) - 1]


def summarize(rows: list[dict], cases: dict) -> dict:
    def subset(pred):
        return [r for r in rows if pred(cases[r["id"]])]

    paged = [r for r in rows if r["predicted"]["escalate"]]
    should = [r for r in rows if r["label"]["escalate"]]
    out = {
        "n": len(rows),
        "severity_correct": sum(r["severity_correct"] for r in rows),
        "escalate_correct": sum(r["escalate_correct"] for r in rows),
        "both_correct": sum(r["severity_correct"] and r["escalate_correct"] for r in rows),
        "pages_sent": len(paged),
        "pages_correct": sum(r["label"]["escalate"] for r in paged),
        "pages_needed": len(should),
        "pages_caught": sum(r["predicted"]["escalate"] for r in should),
    }
    for name, pred in [
        ("context_needed", lambda c: c["context_needed"]),
        ("context_not_needed", lambda c: not c["context_needed"]),
        ("disagree", lambda c: (c["label"]["severity"] == "high") != c["label"]["escalate"]),
    ]:
        part = subset(pred)
        out[name] = {"n": len(part),
                     "severity_correct": sum(r["severity_correct"] for r in part),
                     "escalate_correct": sum(r["escalate_correct"] for r in part)}

    confusion = {gold: {pred: 0 for pred in ["high", "medium", "low"]} for gold in ["high", "medium", "low"]}
    for r in rows:
        confusion[r["label"]["severity"]][r["predicted"]["severity"]] += 1
    out["severity_confusion"] = confusion
    return out


def main() -> None:
    cases = {c["id"]: c for c in load_cases()}
    results = {mode: load(mode) for mode, _ in MODES}
    e2e = load("e2e")
    e2e_rules = load("e2e_rules")
    metrics: dict = {"modes": {}, "calls": {}}
    lines = ["# Eval metrics", "", f"{len(cases)} cases (`eval/eval_errors.json`). Generated by `eval/score.py`.", ""]

    lines += ["## Severity and escalation accuracy (all 48 cases)", "",
              "| Assessor | Severity | Escalation | Both right | Pages sent (correct) | Needed pages caught |",
              "| --- | --- | --- | --- | --- | --- |"]
    for mode, label in MODES:
        if not results[mode]:
            continue
        s = summarize(results[mode]["rows"], cases)
        metrics["modes"][mode] = s
        metrics["calls"][mode] = results[mode]["gemini_calls"]
        lines.append(
            f"| {label} | {pct(s['severity_correct'], s['n'])} | {pct(s['escalate_correct'], s['n'])} | "
            f"{pct(s['both_correct'], s['n'])} | {s['pages_sent']} ({s['pages_correct']}) | "
            f"{pct(s['pages_caught'], s['pages_needed'])} |")

    lines += ["", "## By case group", "",
              "| Assessor | Code-dependent cases: severity / escalation | Other cases: severity / escalation | Severity-vs-escalation disagreements: severity / escalation |",
              "| --- | --- | --- | --- |"]
    for mode, label in MODES:
        if mode not in metrics["modes"]:
            continue
        s = metrics["modes"][mode]
        cells = [f"{pct(s[g]['severity_correct'], s[g]['n'])} / {pct(s[g]['escalate_correct'], s[g]['n'])}"
                 for g in ["context_needed", "context_not_needed", "disagree"]]
        lines.append(f"| {label} | " + " | ".join(cells) + " |")

    lines += ["", "## Severity confusion (rows = label, columns = predicted high / medium / low)", ""]
    for mode, label in MODES:
        if mode not in metrics["modes"]:
            continue
        c = metrics["modes"][mode]["severity_confusion"]
        lines.append(f"- **{label}:** " + "; ".join(
            f"{gold}: {c[gold]['high']}/{c[gold]['medium']}/{c[gold]['low']}" for gold in ["high", "medium", "low"]))

    if results["llm"] and results["llm_repo"]:
        llm = {r["id"]: r for r in results["llm"]["rows"]}
        repo = {r["id"]: r for r in results["llm_repo"]["rows"]}
        fixed = [i for i in repo if repo[i]["severity_correct"] and repo[i]["escalate_correct"]
                 and not (llm[i]["severity_correct"] and llm[i]["escalate_correct"])]
        broke = [i for i in repo if llm[i]["severity_correct"] and llm[i]["escalate_correct"]
                 and not (repo[i]["severity_correct"] and repo[i]["escalate_correct"])]
        metrics["context_effect"] = {"fixed": fixed, "broke": broke}
        lines += ["", "## What GitHub context changed (both fields right vs. not)", "",
                  f"- Fixed by context ({len(fixed)}): {', '.join(fixed) or 'none'}",
                  f"- Broken by context ({len(broke)}): {', '.join(broke) or 'none'}"]

    if e2e:
        rows = e2e["rows"]
        dash = [r["dashboard_latency_ms"] for r in rows]
        server = [r["server_latency_ms"] for r in rows]
        model = [r["assessor_ms"] for r in rows if r["assessor_ms"] is not None]
        lat = {
            "n": len(rows),
            "dashboard_p50": nearest_rank(dash, 50), "dashboard_p95": nearest_rank(dash, 95), "dashboard_max": max(dash),
            "server_p50": nearest_rank(server, 50), "server_p95": nearest_rank(server, 95), "server_max": max(server),
            "model_p50": nearest_rank(model, 50), "model_p95": nearest_rank(model, 95),
        }
        metrics["latency_llm_repo"] = lat
        metrics["calls"]["e2e"] = e2e["gemini_calls"]
        lines += ["", f"## Latency: webhook received -> assessment shown on dashboard ({lat['n']} cases, LLM + GitHub context)", "",
                  "| Measure | p50 | p95 | max |", "| --- | --- | --- | --- |",
                  f"| Webhook POST -> row shows assessment in browser | {lat['dashboard_p50']} ms | {lat['dashboard_p95']} ms | {lat['dashboard_max']} ms |",
                  f"| Server: incident saved -> assessment saved | {lat['server_p50']} ms | {lat['server_p95']} ms | {lat['server_max']} ms |",
                  f"| Gemini call inside the assessor | {lat['model_p50']} ms | {lat['model_p95']} ms | {max(model)} ms |"]
        if e2e_rules:
            rdash = [r["dashboard_latency_ms"] for r in e2e_rules["rows"]]
            rserver = [r["server_latency_ms"] for r in e2e_rules["rows"]]
            metrics["latency_rules"] = {"dashboard_p50": nearest_rank(rdash, 50), "dashboard_p95": nearest_rank(rdash, 95),
                                        "server_p50": nearest_rank(rserver, 50), "server_p95": nearest_rank(rserver, 95)}
            lines.append(f"| Same pipeline with the rules assessor (no LLM): dashboard / server | "
                         f"{metrics['latency_rules']['dashboard_p50']} / {metrics['latency_rules']['server_p50']} ms | "
                         f"{metrics['latency_rules']['dashboard_p95']} / {metrics['latency_rules']['server_p95']} ms | - |")
        lines += ["", "The dashboard polls every 4 s, so the browser number includes 0-4 s of polling delay; "
                  "webhooks are sent at a random point in the poll cycle (seeded)."]

        if results["llm_repo"]:
            offline = {r["id"]: r for r in results["llm_repo"]["rows"]}
            same_sev = sum(r["predicted"]["severity"] == offline[r["id"]]["predicted"]["severity"] for r in rows)
            same_esc = sum(r["predicted"]["escalate"] == offline[r["id"]]["predicted"]["escalate"] for r in rows)
            changed = [r["id"] for r in rows if r["predicted"] != offline[r["id"]]["predicted"]]
            s = summarize(rows, cases)
            metrics["consistency"] = {"n": len(rows), "same_severity": same_sev, "same_escalate": same_esc, "changed": changed}
            metrics["e2e_accuracy"] = {"severity_correct": s["severity_correct"], "escalate_correct": s["escalate_correct"], "n": s["n"]}
            lines += ["", f"## Run-to-run consistency (LLM + GitHub context, {len(rows)} overlapping cases)", "",
                      "Same inputs, temperature 0, offline run vs. end-to-end run:", "",
                      f"- Same severity: {pct(same_sev, len(rows))}",
                      f"- Same escalation: {pct(same_esc, len(rows))}",
                      f"- Cases that changed: {', '.join(changed) or 'none'}",
                      f"- End-to-end run accuracy on these cases: severity {pct(s['severity_correct'], s['n'])}, "
                      f"escalation {pct(s['escalate_correct'], s['n'])}"]

    ledger = RESULTS_DIR / "gemini_calls.log"
    total = len(ledger.read_text(encoding="utf-8").splitlines()) if ledger.exists() else 0
    metrics["calls"]["total_ledger"] = total
    lines += ["", "## Gemini calls", "",
              f"Total attempts recorded in `eval/results/gemini_calls.log`: {total} (budget 170). "
              "Per run: " + ", ".join(f"{k}={v}" for k, v in metrics["calls"].items() if k != "total_ledger") +
              ". The remainder are one aborted end-to-end attempt and one screenshot retake."]

    (RESULTS_DIR / "metrics.json").write_text(json.dumps(metrics, indent=2) + "\n", encoding="utf-8")
    (RESULTS_DIR / "metrics.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
